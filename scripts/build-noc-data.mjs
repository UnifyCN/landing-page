// Regenerates src/lib/noc-2021.ts from the official Statistics Canada NOC 2021
// classification-structure CSV. Run from repo root:
//
//   node scripts/build-noc-data.mjs
//
// The TEER of a unit group is the second digit of its 5-digit code. Every
// /teer/[tier] page lists the full set of unit groups for its tier from this file.

import { writeFileSync } from 'node:fs';

const SOURCE =
  'https://www.statcan.gc.ca/en/subjects/standard/noc/2021/indexV1/noc-2021-v1.0-classification-structure.csv';
const OUT = new URL('../src/lib/noc-2021.ts', import.meta.url);

const res = await fetch(SOURCE, { headers: { 'User-Agent': 'Mozilla/5.0 (Macintosh; Intel Mac OS X 10_15_7)' } });
if (!res.ok) throw new Error(`StatCan CSV fetch failed: HTTP ${res.status}`);
const raw = (await res.text()).replace(/^﻿/, '');

// Minimal RFC 4180 parser (fields may contain quoted commas and newlines).
function parseCSV(s) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (quoted) {
      if (c === '"') { if (s[i + 1] === '"') { field += '"'; i++; } else quoted = false; }
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (c !== '\r') field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const rows = parseCSV(raw).slice(1);
const groups = rows
  .filter((r) => r[0] === '5' && r[2])
  .map((r) => {
    const noc = r[2].padStart(5, '0');
    return { noc, title: r[3].trim(), teer: Number(noc[1]) };
  })
  .sort((a, b) => a.noc.localeCompare(b.noc));

if (groups.length < 500) throw new Error(`Only ${groups.length} unit groups parsed; expected ~516.`);
const seen = new Set();
for (const g of groups) {
  if (!/^\d{5}$/.test(g.noc) || seen.has(g.noc)) throw new Error(`Bad or duplicate NOC code: ${g.noc}`);
  seen.add(g.noc);
}

const lines = groups.map((g) => `  { noc: ${JSON.stringify(g.noc)}, title: ${JSON.stringify(g.title)} },`);
const ts = `// GENERATED by scripts/build-noc-data.mjs. Do not edit by hand.
// Source: ${SOURCE}
// NOC 2021 Version 1.0, ${groups.length} unit groups. The TEER is the 2nd digit of the code.

export interface NocUnitGroup {
  noc: string;
  title: string;
}

export const NOC_2021_UNIT_GROUPS: NocUnitGroup[] = [
${lines.join('\n')}
];

/** All NOC 2021 unit groups whose TEER (2nd digit of the code) equals \`tier\`. */
export const unitGroupsForTeer = (tier: number): NocUnitGroup[] =>
  NOC_2021_UNIT_GROUPS.filter((g) => Number(g.noc[1]) === tier);
`;
writeFileSync(OUT, ts);
const perTeer = groups.reduce((m, g) => ((m[g.teer] = (m[g.teer] || 0) + 1), m), {});
console.log(`wrote src/lib/noc-2021.ts: ${groups.length} unit groups`, perTeer);
